# MCP GitHub Integration Test Script
# This script tests that GitHub API is accessible and token works

param(
    [Parameter(Mandatory=$false)]
    [string]$Token = "",

    [Parameter(Mandatory=$false)]
    [string]$Repository = "garin87/gdm_v5"
)

# Color output functions
function Write-Success { param($Message) Write-Host "? $Message" -ForegroundColor Green }
function Write-Error { param($Message) Write-Host "? $Message" -ForegroundColor Red }
function Write-Info { param($Message) Write-Host "??  $Message" -ForegroundColor Cyan }
function Write-Warning { param($Message) Write-Host "??  $Message" -ForegroundColor Yellow }
function Write-Step { param($Message) Write-Host "`n?? $Message" -ForegroundColor Yellow }

Write-Host @"

????????????????????????????????????????????????????????????
?   MCP GitHub Integration Test                            ?
?   Testing GitHub integration through MCP                 ?
????????????????????????????????????????????????????????????

"@ -ForegroundColor Cyan

# Check token
if ([string]::IsNullOrEmpty($Token)) {
    Write-Warning "GitHub token not provided."
    Write-Info "Run script with parameter: .\test-mcp-integration.ps1 -Token 'your_token'"
    Write-Info "Or create token at: https://github.com/settings/tokens"
    Write-Info ""
    Write-Info "Continuing test without token (limited access)..."
    $useToken = $false
} else {
    Write-Success "Token provided"
    $useToken = $true
}

# Request headers
$headers = @{
    "Accept" = "application/vnd.github.v3+json"
    "User-Agent" = "MCP-Test-Script"
}

if ($useToken) {
    $headers["Authorization"] = "token $Token"
}

# ???????????????????????????????????????????????????????????
# Test 1: Check Node.js
# ???????????????????????????????????????????????????????????
Write-Step "Test 1: Checking Node.js and npm"

try {
    $nodeVersion = node --version 2>&1
    if ($nodeVersion -match "v\d+\.\d+\.\d+") {
        Write-Success "Node.js installed: $nodeVersion"
    } else {
        Write-Error "Node.js not found or installed incorrectly"
        Write-Info "Download Node.js: https://nodejs.org/"
        exit 1
    }
} catch {
    Write-Error "Node.js not found in PATH"
    Write-Info "Install Node.js: https://nodejs.org/"
    exit 1
}

try {
    $npmVersion = npm --version 2>&1
    Write-Success "npm installed: v$npmVersion"
} catch {
    Write-Error "npm not found"
    exit 1
}

# ???????????????????????????????????????????????????????????
# Test 2: Check GitHub API availability
# ???????????????????????????????????????????????????????????
Write-Step "Test 2: Checking GitHub API availability"

try {
    $response = Invoke-RestMethod -Uri "https://api.github.com" -Headers $headers -TimeoutSec 10
    Write-Success "GitHub API is accessible"

    # Check rate limit
    $rateLimitResponse = Invoke-WebRequest -Uri "https://api.github.com/rate_limit" -Headers $headers
    $rateLimit = $rateLimitResponse.Content | ConvertFrom-Json

    if ($useToken) {
        $limit = $rateLimit.rate.limit
        $remaining = $rateLimit.rate.remaining
        $resetTime = [DateTimeOffset]::FromUnixTimeSeconds($rateLimit.rate.reset).LocalDateTime

        Write-Info "Rate Limit: $remaining / $limit requests remaining"
        Write-Info "Limit resets at: $($resetTime.ToString('HH:mm:ss'))"

        if ($remaining -lt 10) {
            Write-Warning "Low number of requests remaining!"
        }
    } else {
        Write-Info "Rate Limit (without token): $($rateLimit.rate.remaining) / $($rateLimit.rate.limit)"
        Write-Warning "Without token, limit is only 60 requests/hour"
    }
} catch {
    Write-Error "Failed to connect to GitHub API"
    Write-Info "Error: $($_.Exception.Message)"
    exit 1
}

# ???????????????????????????????????????????????????????????
# Test 3: Check token (if provided)
# ???????????????????????????????????????????????????????????
if ($useToken) {
    Write-Step "Test 3: Checking GitHub token"

    try {
        $user = Invoke-RestMethod -Uri "https://api.github.com/user" -Headers $headers
        Write-Success "Token is valid!"
        Write-Info "User: $($user.login)"
        Write-Info "Name: $($user.name)"
        Write-Info "Email: $($user.email)"

        # Check scopes
        $scopesResponse = Invoke-WebRequest -Uri "https://api.github.com/user" -Headers $headers
        $scopes = $scopesResponse.Headers["X-OAuth-Scopes"]

        if ($scopes) {
            Write-Info "Token scopes: $scopes"

            if ($scopes -match "repo" -or $scopes -match "public_repo") {
                Write-Success "Token has access to repositories"
            } else {
                Write-Warning "Token does not have 'public_repo' or 'repo' scope"
                Write-Info "MCP requires at least 'public_repo' scope"
            }
        }
    } catch {
        Write-Error "Token is invalid or expired"
        Write-Info "Error: $($_.Exception.Message)"
        Write-Info "Create new token: https://github.com/settings/tokens"
        exit 1
    }
}

# ???????????????????????????????????????????????????????????
# Test 4: Check repository access
# ???????????????????????????????????????????????????????????
Write-Step "Test 4: Checking access to repository $Repository"

try {
    $repo = Invoke-RestMethod -Uri "https://api.github.com/repos/$Repository" -Headers $headers
    Write-Success "Repository found and accessible!"
    Write-Info "Name: $($repo.full_name)"
    Write-Info "Description: $($repo.description)"
    Write-Info "Language: $($repo.language)"
    Write-Info "Private: $(if($repo.private){'Yes'}else{'No'})"
    Write-Info "Stars: $($repo.stargazers_count)"
    Write-Info "Forks: $($repo.forks_count)"
} catch {
    Write-Error "Failed to access repository"
    Write-Info "Error: $($_.Exception.Message)"

    if ($_.Exception.Response.StatusCode -eq 404) {
        Write-Warning "Repository not found or inaccessible"
    } elseif ($_.Exception.Response.StatusCode -eq 401) {
        Write-Warning "Authentication required (token needed)"
    } elseif ($_.Exception.Response.StatusCode -eq 403) {
        Write-Warning "Access denied (check token permissions)"
    }

    exit 1
}

# ???????????????????????????????????????????????????????????
# Test 5: Retrieve Issues (main MCP function)
# ???????????????????????????????????????????????????????????
Write-Step "Test 5: Retrieving Issues from repository"

try {
    $issues = Invoke-RestMethod -Uri "https://api.github.com/repos/$Repository/issues?state=all&per_page=10" -Headers $headers

    if ($issues.Count -gt 0) {
        Write-Success "Issues retrieved! Total found: $($issues.Count)"
        Write-Info ""
        Write-Info "Recent Issues:"
        Write-Info "?????????????????????????????????????????????????????????"

        $issues | Select-Object -First 5 | ForEach-Object {
            $stateColor = if ($_.state -eq "open") { "Green" } else { "Gray" }
            Write-Host "  #$($_.number) " -NoNewline -ForegroundColor White
            Write-Host "[$($_.state)] " -NoNewline -ForegroundColor $stateColor
            Write-Host "$($_.title)" -ForegroundColor White
            Write-Host "      ?? $($_.user.login) | ?? $($_.comments) comments" -ForegroundColor DarkGray
        }

        Write-Info "?????????????????????????????????????????????????????????"
    } else {
        Write-Warning "No issues found in repository"
        Write-Info "This is normal for a new repository"
    }

    Write-Success "? MCP will be able to retrieve Issues from this repository"

} catch {
    Write-Error "Failed to retrieve Issues"
    Write-Info "Error: $($_.Exception.Message)"
}

# ???????????????????????????????????????????????????????????
# Test 6: Check comments (if issues exist)
# ???????????????????????????????????????????????????????????
if ($issues.Count -gt 0 -and $issues[0].comments -gt 0) {
    Write-Step "Test 6: Retrieving comments"

    try {
        $issueNumber = $issues[0].number
        $comments = Invoke-RestMethod -Uri "https://api.github.com/repos/$Repository/issues/$issueNumber/comments" -Headers $headers

        Write-Success "Comments retrieved! Total: $($comments.Count)"

        if ($comments.Count -gt 0) {
            Write-Info "First comment:"
            Write-Host "  ?? $($comments[0].user.login): " -NoNewline -ForegroundColor Cyan
            Write-Host "$($comments[0].body.Substring(0, [Math]::Min(100, $comments[0].body.Length)))..." -ForegroundColor White
        }

        Write-Success "? MCP will be able to retrieve comments on Issues"
    } catch {
        Write-Warning "Failed to retrieve comments"
    }
}

# ???????????????????????????????????????????????????????????
# Test 7: Check MCP server (if npx is available)
# ???????????????????????????????????????????????????????????
Write-Step "Test 7: Checking MCP server"

try {
    Write-Info "Checking @modelcontextprotocol/server-github availability..."

    # Check if package is installed
    $npmList = npm list -g @modelcontextprotocol/server-github 2>&1

    if ($npmList -match "@modelcontextprotocol/server-github") {
        Write-Success "MCP GitHub server installed globally"
    } else {
        Write-Info "MCP server not installed globally (this is normal)"
        Write-Info "npx will automatically download it when needed"
    }

    Write-Success "? MCP server can be launched via npx"

} catch {
    Write-Warning "Failed to check MCP server installation"
}

# ???????????????????????????????????????????????????????????
# Final Report
# ???????????????????????????????????????????????????????????
Write-Host "`n" -NoNewline
Write-Host "????????????????????????????????????????????????????????????" -ForegroundColor Green
Write-Host "?               TEST SUMMARY                             ?" -ForegroundColor Green
Write-Host "????????????????????????????????????????????????????????????" -ForegroundColor Green
Write-Host ""

Write-Success "Node.js and npm installed"
Write-Success "GitHub API accessible"

if ($useToken) {
    Write-Success "Token valid and working"
} else {
    Write-Warning "Token not provided (limited access)"
}

Write-Success "Repository $Repository accessible"

if ($issues.Count -gt 0) {
    Write-Success "Issues successfully retrieved ($($issues.Count) items)"
} else {
    Write-Info "Issues not found (new repository?)"
}

Write-Host ""
Write-Host "???????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host "  READY FOR MCP USE!" -ForegroundColor Green
Write-Host "???????????????????????????????????????????????????????????" -ForegroundColor Cyan
Write-Host ""

# Recommendations
Write-Host "?? NEXT STEPS:" -ForegroundColor Yellow
Write-Host ""

if (-not $useToken) {
    Write-Host "1. Create GitHub Personal Access Token:" -ForegroundColor White
    Write-Host "   https://github.com/settings/tokens" -ForegroundColor Cyan
    Write-Host "   Scope: public_repo (for public repositories)" -ForegroundColor Gray
    Write-Host ""
}

Write-Host "2. Configure AI client (Claude Desktop or VS Code):" -ForegroundColor White
Write-Host "   See file: .ai\MCP_QUICK_START.md" -ForegroundColor Cyan
Write-Host ""

Write-Host "3. Add token to AI client configuration" -ForegroundColor White
Write-Host ""

Write-Host "4. Restart AI client" -ForegroundColor White
Write-Host ""

Write-Host "5. Test with query:" -ForegroundColor White
Write-Host '   "List all issues in garin87/gdm_v5"' -ForegroundColor Cyan
Write-Host ""

Write-Host "???????????????????????????????????????????????????????????" -ForegroundColor Cyan

# Save results
$timestamp = Get-Date -Format "yyyy-MM-dd_HH-mm-ss"
$reportPath = "mcp-test-report-$timestamp.txt"

@"
MCP GitHub Integration Test Report
Generated: $(Get-Date -Format "yyyy-MM-dd HH:mm:ss")
Repository: $Repository
Token Provided: $useToken
Node.js: $nodeVersion
npm: v$npmVersion
Issues Found: $($issues.Count)
Test Result: SUCCESS
"@ | Out-File -FilePath $reportPath -Encoding UTF8

Write-Host ""
Write-Info "Report saved: $reportPath"
